import { z } from "zod";

import { hoursSchema, isoDateTimeSchema, serviceTypeSchema, uuidSchema } from "./common";

export const BRIEF_MIN_LENGTH = 20;
export const BRIEF_MAX_LENGTH = 10_000;
export const MAX_DELIVERABLES = 30;
export const MAX_ANALYSIS_NOTES = 15;

// POST /api/briefs/analyze
export const analyzeBriefRequestSchema = z.strictObject({
  brief: z.string().trim().min(BRIEF_MIN_LENGTH).max(BRIEF_MAX_LENGTH),
  serviceType: serviceTypeSchema,
});
export type AnalyzeBriefRequest = z.infer<typeof analyzeBriefRequestSchema>;

// A final deliverable always has a reasonable hour estimate. Work that cannot
// be estimated from the brief is not listed here; it is asked about in
// clarificationQuestions instead of receiving a made-up number.
export const deliverableSchema = z.object({
  id: uuidSchema, // generated by the server
  title: z.string().trim().min(1).max(200),
  description: z.string().trim().max(2_000),
  estimatedHours: hoursSchema,
});
export type DeliverableItem = z.infer<typeof deliverableSchema>;

// Structured analysis of a brief. It never contains prices: pricing comes from
// the freelancer's rate and is computed by the quote engine.
export const briefAnalysisSchema = z
  .object({
    summary: z.string().trim().min(1).max(2_000),
    deliverables: z.array(deliverableSchema).max(MAX_DELIVERABLES),
    clarificationQuestions: z.array(z.string().trim().min(1).max(500)).max(MAX_ANALYSIS_NOTES),
    assumptions: z.array(z.string().trim().min(1).max(500)).max(MAX_ANALYSIS_NOTES),
  })
  .refine((analysis) => analysis.deliverables.length > 0 || analysis.clarificationQuestions.length > 0, {
    message: "An analysis needs at least one deliverable or clarification question",
    path: ["deliverables"],
  });
export type BriefAnalysis = z.infer<typeof briefAnalysisSchema>;

export const analyzeBriefResponseSchema = z.object({
  briefId: uuidSchema,
  serviceType: serviceTypeSchema,
  analysis: briefAnalysisSchema,
  // Sum of analysis.deliverables[].estimatedHours, computed on the server.
  totalEstimatedHours: z.number().nonnegative(),
  createdAt: isoDateTimeSchema,
});
export type AnalyzeBriefResponse = z.infer<typeof analyzeBriefResponseSchema>;
